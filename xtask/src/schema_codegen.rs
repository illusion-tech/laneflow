    #[test]
    fn strip_non_code_removes_comments_and_literals() {
        // 注释与字面量内容消失，代码 token 原样保留。
        let stripped = strip_non_code(
            "fn f() { unsafe { g() } } // unsafe in comment\n\
             /* block unsafe */ /* nested /* deep unsafe */ still */ let s = \"unsafe in string\";\n\
             let b = b\"unsafe bytes\"; let c = c\"unsafe cstr\";\n\
             let r = r\"unsafe raw\"; let r2 = r##\"unsafe \"quoted\" raw\"##;\n\
             /// doc comment unsafe\n\
             fn documented() {}\n\
             ",
        );
        assert_eq!(count_unsafe_tokens(&stripped), 1, "{stripped}");
        assert!(stripped.contains("fn f()"), "{stripped}");
        assert!(stripped.contains("let s ="), "{stripped}");
        assert!(stripped.contains("fn documented()"), "{stripped}");
        // 生命周期不是字符字面量，后面的代码必须保留。
        let stripped = strip_non_code("fn f<'a>(x: &'a str) -> &'a str { x }");
        assert!(stripped.contains("'a"), "{stripped}");
        assert!(stripped.contains("-> &'a str"), "{stripped}");
        // 字符字面量整体 strip，包括转义形态。
        assert!(!strip_non_code("let c = 'u';").contains('u'));
        assert_eq!(strip_non_code("let q = '\\'';").trim(), "let q =  ;");
        assert_eq!(
            count_unsafe_tokens(&strip_non_code("let e = '\\u{1f600}';")),
            0
        );
        // 块注释未闭合 / 字符串未闭合：strip 到文件尾，不 panic。
        assert_eq!(strip_non_code("ok(); /* dangling unsafe"), "ok();  ");
        assert_eq!(strip_non_code("let s = \"dangling unsafe"), "let s =  ");
        // unsafe 被注释拆半不产生 token，也不与 strip 残留粘连成 token。
        assert_eq!(count_unsafe_tokens(&strip_non_code("uns/* */afe")), 0);
        assert_eq!(count_unsafe_tokens(&strip_non_code("unsafe/*x*/{}")), 1);
    }

