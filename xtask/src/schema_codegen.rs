//! FlatBuffers wire 生成物与受审计 `unsafe` 边界检查。
//!
//! 覆盖道路编辑（`LFRE`）与运行时快照（`LFRS`）两个私有 wire 家族；两者共用
//! 固定 flatc 版本、Rust canonical bytes clean-regeneration 比对、C++/C# probe。
//! unsafe 边界由 `check-wire-audit`（见 wire_audit.rs 模块文档）以 hermetic 编译
//! 与钉版断言闭合。

use std::collections::HashSet;
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub(crate) const FLATBUFFERS_VERSION: &str = "25.12.19";
const GENERATED_HEADER: &[u8] =
    b"// automatically generated by the FlatBuffers compiler, do not modify\n// @generated\n";
const AUDITED_MMAP_MANIFEST_PATH: &str = "crates/laneflow-format-mmap/Cargo.toml";
const AUDITED_MMAP_PACKAGE_ROOT: &str = "crates/laneflow-format-mmap";
const AUDITED_MMAP_SOURCE_PATH: &str = "crates/laneflow-format-mmap/src/lib.rs";
const AUDITED_MMAP_EXPRESSION: &str = "unsafe { MmapOptions::new().len(expected).map(&self.file) }";

/// 一个私有 wire 家族的固定路径与命令面。
pub(crate) struct WireFamily {
    /// 中文标签，用于输出与错误信息。
    pub(crate) label: &'static str,
    /// 对应的 xtask 命令名。
    pub(crate) command: &'static str,
    /// schema 相对路径。
    pub(crate) schema_path: &'static str,
    /// checked-in Rust 生成物相对路径。
    pub(crate) checked_rust_path: &'static str,
    /// wire crate manifest 相对路径。
    pub(crate) wire_manifest_path: &'static str,
    /// wire crate 根相对路径。
    pub(crate) wire_package_root: &'static str,
    /// wire crate 包名（flatbuffers 钉版核对目标）。
    pub(crate) wire_package_name: &'static str,
    /// codegen 输出目录相对路径。
    pub(crate) output_root: &'static str,
    /// flatc 产出的 Rust 文件名。
    pub(crate) generated_rust_file: &'static str,
}

